import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test('Catalina activates her account, publishes packages and sees them from another browser', async ({ page, browser }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/admin#setup=browser-test-token');
  await expect(page.getByRole('heading', { name: 'Activa tu espacio.' })).toBeVisible();
  await page.getByLabel('Correo electrónico').fill('catalina@example.com');
  await page.getByLabel('Contraseña', { exact: true }).fill('private-browser-password');
  await page.getByRole('button', { name: 'Crear mi cuenta' }).click();
  await expect(page.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible();
  await page.locator('[data-view="catalog"]').click();
  await page.getByRole('button', { name: '+ Crear paquete' }).click();
  await page.getByLabel('Nombre', { exact: true }).fill('Sesión con Catalina');
  await page.getByLabel('Precio (MXN)').fill('950.50');
  await page.getByLabel('Descripción', { exact: true }).fill('Una sesión individual de acompañamiento.');
  await page.getByLabel('Visible en la página').check();
  await page.getByRole('button', { name: 'Crear paquete', exact: true }).click();
  await expect(page.getByText('Guardado. Los cambios ya están disponibles en tu página de pago.')).toBeVisible();
  const visitor = await browser.newContext(); const publicPage = await visitor.newPage();
  await publicPage.goto('http://localhost:3000');
  await expect(publicPage.getByRole('heading', { name: 'Sesión con Catalina' })).toBeVisible();
  await expect(publicPage.locator('#total')).toContainText('950.50');
  await expect(publicPage.getByRole('button', { name: 'Continuar al pago' })).toBeDisabled();
  await publicPage.goto('http://localhost:3000/admin');
  await expect(publicPage.getByRole('heading', { name: 'Bienvenida.' })).toBeVisible();
  await expect(publicPage.getByRole('button', { name: 'Cerrar sesión' })).toBeHidden();
  await visitor.close();
  await page.getByLabel('Visible en la página').uncheck();
  await page.getByRole('button', { name: 'Guardar cambios' }).click();
  await expect(page.getByLabel('Visible en la página')).not.toBeChecked();
  await page.getByRole('button', { name: 'Cerrar sesión' }).click();
  await expect(page.getByRole('heading', { name: 'Bienvenida.' })).toBeVisible();
  await page.getByLabel('Correo electrónico').fill('catalina@example.com');
  await page.getByLabel('Contraseña', { exact: true }).fill('private-browser-password');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible();
  await page.locator('[data-view="account"]').click();
  await page.getByLabel('Correo de la persona invitada').fill('catalina.new@example.com');
  await page.getByRole('button', { name: 'Crear invitación', exact: true }).click();
  await expect(page.locator('#invite-link')).not.toHaveValue('');
  const inviteUrl = await page.locator('#invite-link').inputValue();
  const catalinaContext = await browser.newContext(); const catalina = await catalinaContext.newPage();
  await catalina.goto(inviteUrl);
  await expect(catalina.getByLabel('Correo electrónico')).toHaveValue('catalina.new@example.com');
  await expect(catalina.getByLabel('Correo electrónico')).toHaveAttribute('readonly', '');
  await catalina.getByLabel('Contraseña', { exact: true }).fill('catalina-private-password');
  await catalina.getByRole('button', { name: 'Crear mi cuenta' }).click();
  await expect(catalina.getByLabel('Código de verificación')).toBeVisible();
  let messages = JSON.parse(await readFile('/tmp/catalina-browser-mail.json', 'utf8'));
  await catalina.getByLabel('Código de verificación').fill(messages.at(-1).code);
  await catalina.getByRole('button', { name: 'Verificar código' }).click();
  await expect(catalina.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible();
  await catalina.locator('[data-view="account"]').click();
  await expect(catalina.locator('#mfa-status')).toContainText('Activada.');
  await expect(catalina.locator('#access-management')).toBeHidden();
  await catalina.getByRole('button', { name: 'Cerrar sesión' }).click();
  await catalina.getByLabel('Correo electrónico').fill('catalina.new@example.com');
  await catalina.getByLabel('Contraseña', { exact: true }).fill('catalina-private-password');
  await catalina.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(catalina.getByLabel('Código de verificación')).toBeVisible();
  await expect(catalina.locator('#workspace')).toBeHidden();
  messages = JSON.parse(await readFile('/tmp/catalina-browser-mail.json', 'utf8'));
  await catalina.getByLabel('Código de verificación').fill(messages.at(-1).code);
  await catalina.getByRole('button', { name: 'Verificar código' }).click();
  await expect(catalina.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible();
  await expect(page.locator('#users-list')).toContainText('catalina.new@example.com');
  await page.getByLabel('Confirma tu contraseña actual').fill('private-browser-password');
  await page.getByRole('button', { name: 'Activar verificación por correo' }).click();
  await expect(page.getByLabel('Código de verificación')).toBeVisible();
  messages = JSON.parse(await readFile('/tmp/catalina-browser-mail.json', 'utf8'));
  await page.getByLabel('Código de verificación').fill(messages.at(-1).code);
  await page.getByRole('button', { name: 'Verificar código' }).click();
  await expect(page.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible();
  await page.locator('[data-view="account"]').click();
  await expect(page.locator('#mfa-status')).toContainText('Activada.');
  await catalina.setViewportSize({ width: 390, height: 844 });
  await catalina.locator('[data-view="account"]').click();
  expect(await catalina.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await catalina.goto(inviteUrl);
  await expect(catalina.locator('#auth-feedback')).toContainText('Invitación inválida o caducada.');
  await catalinaContext.close();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('[data-view="catalog"]').click();
  await expect(page.getByRole('heading', { name: 'Tus paquetes.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
